@with_config(ConfigDict(extra="forbid"))
class ReleaseCheck(TypedDict):
    code: Literal[
        "network_checks",
        "basis_missing",
        "pp616_pending",
        "pp616_reference",
        "pp1160_pending",
        "pp1160_reference",
        "reviewer_missing",
        "hard_errors",
        "species_missing",
    ]
    count: NotRequired[Annotated[int, Field(gt=0)]]


@with_config(ConfigDict(extra="forbid"))
class FailureParams(TypedDict, total=False):
    component_count: int
    http_status: int
    zone_ids: list[str]
    zone_label: str
    other_zone_label: str
    max_candidates: int
    layer_names: list[str]
    release_checks: Annotated[list[ReleaseCheck], Field(min_length=1)]
    species_revision_id: str
    expected_kind: Literal["tree", "shrub"]
    actual_kind: Literal["tree", "shrub"]


class DomainFailure(ValueError):
    def __init__(
        self, reason: FailureReason, params: FailureParams | None = None
    ) -> None:
        self.reason = reason
        self.params: FailureParams = params or {}
        super().__init__()


class ProjectNotFound(KeyError):
    def __init__(self, project_id: str) -> None:
        self.project_id = project_id
        super().__init__()


class ResourceNotFound(KeyError):
    def __init__(
        self, reason: FailureReason, params: FailureParams | None = None
    ) -> None:
        self.reason = reason
        self.params: FailureParams = params or {}
        super().__init__()
